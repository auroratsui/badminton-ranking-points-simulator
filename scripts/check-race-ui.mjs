import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { rankingPlayers } from '../lib/ranking-data.ts';
import { findRacePlayer, projectRacePoints } from '../lib/race-to-finals.ts';
const data = JSON.parse(await readFile(new URL('../lib/race-to-finals-data.json',import.meta.url)));
const browser = await chromium.launch();
try {
 const page = await browser.newPage({viewport:{width:1440,height:1150}});
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://localhost:3000/', {waitUntil:'networkidle'});
 const box = page.getByText('Projected Race-to-Finals Points',{exact:true}).locator('..');
 const choosePlayer = async name => {
   await page.getByRole('textbox',{name:'Player 1 name',exact:true}).fill(name);
   await page.getByRole('option').filter({hasText:name}).first().click();
 };
 assert.equal(await box.count(),0);
 await choosePlayer('Christo POPOV');
 assert.equal(await box.count(),1);
 assert.match(await box.innerText(),/---/);
 await page.getByRole('textbox',{name:'Tournament Name',exact:true}).fill('Hylo');
 await page.getByRole('option').filter({hasText:/HYLO Open 2026/i}).click();
 await page.getByLabel('Christo POPOV hypothetical result',{exact:true}).selectOption('winner');
 const selected = rankingPlayers.find(p=>p.name==='Christo POPOV' && p.code==='MS');
 const expected=projectRacePoints(data,findRacePlayer(data,selected),{week:await page.getByLabel('Tournament Week',{exact:true}).inputValue(),level:await page.getByLabel('Tournament Level',{exact:true}).inputValue(),points:9200,team:false});
 assert.ok((await box.innerText()).includes(expected.points.toLocaleString('en-GB')));
 await page.screenshot({path:'/tmp/bwf-race-desktop.png',fullPage:true,animations:'disabled'});
 await page.getByLabel('Tournament Week',{exact:true}).selectOption('2026-W48');
 assert.match(await box.getAttribute('title'),/2027 season/);
 assert.match(await box.innerText(),/from 0/);
 assert.ok(!(await box.getAttribute('title')).endsWith('.'));
 await page.getByRole('button',{name:'About Race-to-Finals points',exact:true}).click();
 assert.ok(await page.getByText('Displayed for players ranked in the top 25 of the Race to Finals',{exact:true}).isVisible());
 await page.keyboard.press('Escape');
 await page.getByText('Displayed for players ranked in the top 25 of the Race to Finals',{exact:true}).waitFor({state:'hidden'});
 await page.getByLabel('Tournament Week',{exact:true}).selectOption('2026-W45');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(() => window.scrollTo(0,0));
 await page.screenshot({path:'/tmp/bwf-race-mobile.png',fullPage:true,animations:'disabled'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.setViewportSize({width:1440,height:1150});
 await page.getByRole('textbox',{name:'Tournament Name',exact:true}).fill('Malaysia Open 2027');
 await page.getByRole('option').filter({hasText:'Malaysia Open 2027'}).click();
 const resultSelect = page.getByLabel('Christo POPOV hypothetical result',{exact:true});
 await resultSelect.selectOption('r64');
 assert.match(await box.innerText(),/1,200/);
 assert.match(await box.innerText(),/from 0/);
 // Previous editions must now come from 2026, not the earlier selected year's list.
 assert.ok(await page.getByLabel('Previous edition from 2026').inputValue());
 await page.getByRole('button',{name:'Generate',exact:true}).first().click();
 assert.ok(await page.getByRole('columnheader',{name:'R64',exact:true}).isVisible());
 await page.getByRole('button',{name:'Generate',exact:true}).last().click();
 assert.equal(await page.getByRole('columnheader',{name:'R64',exact:true}).count(),2);
 await page.getByLabel('Tournament Level',{exact:true}).selectOption('chinaOpen');
 await resultSelect.selectOption('r64');
 assert.match(await box.innerText(),/1,350/);
 await page.getByLabel('Tournament Week',{exact:true}).selectOption('2026-W45');
 assert.equal(await resultSelect.locator('option[value="r64"]').count(),0);
 assert.equal(await resultSelect.inputValue(),'');
 const outside=rankingPlayers.find(p=>p.code==='MS' && !findRacePlayer(data,p));
 await choosePlayer(outside.name);
 assert.equal(await box.count(),0);
 await page.getByRole('tab',{name:'Crystal Ball',exact:true}).click();
 await choosePlayer('Christo POPOV');
 assert.equal(await box.count(),0);
 await page.getByRole('textbox',{name:'Tournament Name',exact:true}).fill('Malaysia Open 2027');
 await page.getByRole('option').filter({hasText:'Malaysia Open 2027'}).click();
 assert.equal(await page.locator('select option[value="r64"]').count(),1);
 assert.deepEqual(errors,[]);
 console.log('PASS: Default-only visibility, top-25 membership, no premature projection, live projection, W48 rollover, help popover, mobile overflow, 2027 R64 options/tables, Crystal Ball R64; no browser errors.');
} finally { await browser.close(); }
